#ifndef SNAPSHOT_RESULT_H
#define SNAPSHOT_RESULT_H
#include <stdint.h>
enum { SNAP_MAGIC=0, SNAP_VERSION=1, SNAP_BYTES=2, SNAP_STATE=3,
    SNAP_SEQUENCE=4, SNAP_RC=5, SNAP_FOUND=6, SNAP_ROI_VALID=7,
    SNAP_X=8, SNAP_Y=9, SNAP_W=10, SNAP_H=11, SNAP_CANDIDATES=12,
    SNAP_OVERFLOW=13, SNAP_RGB_ADDR=14, SNAP_RGB_BYTES=15, SNAP_STRIDE=16,
    SNAP_GRAY_ADDR=17, SNAP_GRAY_BYTES=18, SNAP_ROI_ADDR=19, SNAP_ROI_BYTES=20,
    SNAP_HZ=21, SNAP_CAPTURE_TICKS=23, SNAP_STOP_TICKS=25,
    SNAP_PREPROCESS_TICKS=27, SNAP_DETECT_TICKS=29, SNAP_ROI_TICKS=31,
    SNAP_TASK_TICKS=33, SNAP_DMA_STATUS=35, SNAP_SENSOR_STATUS=36,
    SNAP_ROI_SIDE=37,
    SNAP_WORDS=40 };
typedef struct { uint32_t word[SNAP_WORDS]; } snapshot_result;
static inline void snapshot_set_ticks(snapshot_result *r, unsigned i, uint64_t v)
{ r->word[i]=(uint32_t)v; r->word[i+1]=(uint32_t)(v>>32); }
#endif
